"""Export the judges deck, one-pager and one-slide from HTML to PDF (and PNG).

These three documents used to be exported by hand, which is how the repo ended
up with verdikt-judges-deck{,-v2,-v3,-v4}.pdf and a submission folder holding
a deck three revisions behind its own HTML. The numbers on the Proof slide are
regenerated by scripts/update_slide_stats.py, so without a renderer every stats
update silently desynchronised the PDF a judge actually opens from the HTML
that is under version control.

    python scripts/render_docs_pdf.py            # all three
    python scripts/render_docs_pdf.py one-slide  # just one

Page geometry comes from each file's own @page rule: the deck and one-slide are
1920x1080 (one CSS px per device px, so the PDF matches the design grid), the
one-pager is Letter. print-background is on because the whole design is
background colour.
"""
from __future__ import annotations

import sys
from pathlib import Path

from playwright.sync_api import sync_playwright

DOCS = Path("docs")

# name -> (html, pdf, pdf kwargs, optional png at this viewport)
TARGETS = {
    "judges-deck": (
        "verdikt-judges-deck.html", "verdikt-judges-deck.pdf",
        {"width": "1920px", "height": "1080px"}, None,
    ),
    "one-pager": (
        "verdikt-one-pager.html", "verdikt-one-pager.pdf",
        {"format": "Letter"}, None,
    ),
    "email-test-guide": (
        "verdikt-email-test-guide.html", "verdikt-email-test-guide.pdf",
        {"format": "Letter"}, None,
    ),
    "one-slide": (
        "verdikt-one-slide.html", "verdikt-one-slide.pdf",
        {"width": "1920px", "height": "1080px"}, (1920, 1080),
    ),
}


def main() -> None:
    wanted = sys.argv[1:] or list(TARGETS)
    unknown = [w for w in wanted if w not in TARGETS]
    if unknown:
        sys.exit(f"unknown target(s): {unknown}. Known: {list(TARGETS)}")

    with sync_playwright() as p:
        browser = p.chromium.launch()
        for name in wanted:
            html, pdf_name, pdf_kwargs, png = TARGETS[name]
            src = (DOCS / html).resolve()
            if not src.exists():
                print(f"[docs] skip {name} — {src} missing")
                continue
            page = browser.new_page(viewport={"width": 1920, "height": 1080})
            page.goto(f"file:///{src.as_posix()}")
            # The design is carried by Instrument Serif; screenshotting or
            # printing before it lands silently falls back to Georgia.
            page.wait_for_timeout(1500)
            out = DOCS / pdf_name
            page.pdf(path=str(out), print_background=True, prefer_css_page_size=False,
                     margin={"top": "0", "right": "0", "bottom": "0", "left": "0"},
                     **pdf_kwargs)
            print(f"[docs] {out}  ({out.stat().st_size // 1024} KB)")
            if png:
                shot = DOCS / f"{Path(pdf_name).stem}.png"
                page.screenshot(path=str(shot),
                                clip={"x": 0, "y": 0, "width": png[0], "height": png[1]})
                print(f"[docs] {shot}  ({shot.stat().st_size // 1024} KB)")
            page.close()
        browser.close()


if __name__ == "__main__":
    main()
